#!/usr/bin/env python3
"""Generates the Buck2 build files from the Cargo workspace.

Usage: build_defs/update_buck_files.py

Run it from any directory after a change to a Cargo.toml or Cargo.lock.
Cargo.toml stays the description of every crate; the build files follow it:

- third-party/rust/BUCK: `reindeer buckify` writes the rules for the
  crates.io dependencies, each listing the reindeer platforms that use it.
- crates/*/BUCK: the rules for each workspace crate. A library becomes
  `:<lib>`, a binary `:<bin>-bin`, and their unit tests `:<lib>-lib-test` and
  `:<bin>-bin-test`; the integration test `tests/<name>.rs` becomes
  `:<name>-test`. A benchmark becomes the executable `:<name>-bench` (only
  `harness = false` benchmarks are supported) and an example
  `:<name>-example`; Buck2 builds and lints them but does not run them.
  Dependencies, dev-dependencies and enabled features come from Cargo's
  resolution for each host. A crate whose resolution changes with
  `--all-features` also gets its library and binaries with `-all-features`
  after the target name, so that builds and lints cover the optional code.
  Tests use the default features only, as `cargo test` does.

Reindeer generates rules and aliases only for the normal dependencies that
the default features enable, and builds each third-party crate with one
feature set. A third-party crate that the workspace uses only as a
dev-dependency or an optional dependency, and a third-party feature that
only `--all-features` enables, must be listed in
third-party/rust/Cargo.toml; the script fails when one is missing. A
feature that only a dev-dependency enables is not detected: Cargo's
resolution includes dev-dependency edges and reindeer's does not, so the
Buck2 test fails to compile instead.
"""

import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY_LABEL = "//third-party/rust"

# Buck2 `prelude//os` constraint names and the Rust host triple used to
# resolve each: the hosts of toolchains/update_rust_release.py, one per OS.
HOSTS = {
    "linux": "x86_64-unknown-linux-gnu",
    "macos": "aarch64-apple-darwin",
    "windows": "x86_64-pc-windows-msvc",
}

# Feature selections and the `cargo metadata` arguments that resolve them.
RESOLUTIONS = {
    "default": [],
    "all-features": ["--all-features"],
}

GENERATED = "# @generated by build_defs/update_buck_files.py"
HEADER = GENERATED + " from {source}; do not edit.\n"

LIBRARY_KINDS = {"lib", "rlib", "dylib", "cdylib", "staticlib", "proc-macro"}


class BuildFileError(Exception):
    pass


class Select:
    def __init__(self, branches):
        self.branches = branches


class Raw(str):
    """Starlark source inserted as written."""


def cargo_metadata(*args):
    output = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", *args],
        cwd=ROOT,
        check=True,
        stdout=subprocess.PIPE,
        text=True,
    ).stdout
    return json.loads(output)


def relative(path):
    return Path(path).resolve().relative_to(ROOT).as_posix()


def starlark(value, indent=0):
    """Renders a str, bool, list, dict, Select or Raw value as Starlark source."""
    pad = "    " * (indent + 1)
    end = "    " * indent
    if isinstance(value, Raw):
        return str(value)
    if isinstance(value, Select):
        return "select({})".format(starlark(value.branches, indent))
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        if not value:
            return "[]"
        return "[\n" + "".join(f"{pad}{starlark(item, indent + 1)},\n" for item in value) + end + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = "".join(f"{pad}{starlark(key)}: {starlark(item, indent + 1)},\n" for key, item in value.items())
        return "{\n" + items + end + "}"
    raise TypeError(f"cannot render {value!r}")


def per_host(values):
    """One value when every host agrees, otherwise a select on the host OS."""
    first = next(iter(values.values()))
    if all(value == first for value in values.values()):
        return first
    return Select({f"prelude//os:{os_name}": value for os_name, value in values.items()})


def call(rule, attributes):
    """Returns the target name and the Starlark source of one rule call."""
    lines = [f"{rule}("]
    for key, value in attributes.items():
        if value is not None:
            lines.append(f"    {key} = {starlark(value, 1)},")
    lines.append(")")
    return attributes["name"], "\n".join(lines) + "\n"


class Workspace:
    def __init__(self):
        metadata = {
            (resolution, os_name): cargo_metadata("--filter-platform", triple, *arguments)
            for resolution, arguments in RESOLUTIONS.items()
            for os_name, triple in HOSTS.items()
        }
        # Each resolution lists only the packages it includes.
        self.packages = {package["id"]: package for host in metadata.values() for package in host["packages"]}
        self.members = [self.packages[member] for member in next(iter(metadata.values()))["workspace_members"]]
        self.nodes = {key: {node["id"]: node for node in host["resolve"]["nodes"]} for key, host in metadata.items()}
        self.directories = {package["id"]: relative(Path(package["manifest_path"]).parent) for package in self.members}

    def node(self, resolution, os_name, package):
        return self.nodes[(resolution, os_name)][package["id"]]

    def is_member(self, package_id):
        return package_id in self.directories

    def crates(self):
        """The workspace members that get crates/*/BUCK files."""
        return [package for package in self.members if self.directories[package["id"]].startswith("crates/")]

    def missing_third_party_features(self):
        """Features that `--all-features` enables on third-party packages and
        the default features do not. Buck2 builds each third-party crate with
        one feature set: the default resolution's."""
        missing = {}
        for os_name in HOSTS:
            default = self.nodes[("default", os_name)]
            for package_id, node in self.nodes[("all-features", os_name)].items():
                if self.is_member(package_id) or package_id not in default:
                    continue
                extra = set(node["features"]) - set(default[package_id]["features"])
                if extra:
                    package = self.packages[package_id]
                    missing.setdefault(f"{package['name']} {package['version']}", set()).update(extra)
        return missing

    def third_party_aliases(self):
        """Labels of the aliases reindeer generates: direct normal dependencies
        under the default features."""
        aliases = set()
        for package in self.members:
            for os_name in HOSTS:
                for dependency in self.node("default", os_name, package)["deps"]:
                    if not self.is_member(dependency["pkg"]) and any(
                        kind["kind"] is None for kind in dependency["dep_kinds"]
                    ):
                        aliases.add(f"{THIRD_PARTY_LABEL}:{self.packages[dependency['pkg']]['name']}")
        return aliases


def library_target(package):
    libraries = [target for target in package["targets"] if LIBRARY_KINDS & set(target["kind"])]
    if len(libraries) > 1:
        raise BuildFileError(f"{package['name']} has {len(libraries)} library targets")
    return libraries[0] if libraries else None


def dependency_labels(workspace, package, node):
    """Returns (normal, dev) labels of the dependencies in one resolution node.

    Workspace dependencies are the default-feature targets: each crate's
    optional code is covered by its own `-all-features` targets.
    """
    normal = set()
    dev = set()
    for dependency in node["deps"]:
        kinds = {kind["kind"] for kind in dependency["dep_kinds"]}
        if kinds - {None, "dev"}:
            raise BuildFileError(f"{package['name']}: build dependencies are not supported")
        dependency_package = workspace.packages[dependency["pkg"]]
        library = library_target(dependency_package)
        if library is None or dependency["name"] != library["name"].replace("-", "_"):
            raise BuildFileError(
                f"{package['name']}: dependency {dependency_package['name']} is renamed to {dependency['name']}"
            )
        if workspace.is_member(dependency["pkg"]):
            label = f"//{workspace.directories[dependency['pkg']]}:{library['name']}"
        else:
            label = f"{THIRD_PARTY_LABEL}:{dependency_package['name']}"
        if None in kinds:
            normal.add(label)
        if "dev" in kinds:
            dev.add(label)
    return normal, dev - normal


def package_env(package):
    version = package["version"]
    core, _, pre = version.partition("-")
    major, minor, patch = core.split("+")[0].split(".")
    return {
        # Relative to the crate's sources; the prelude makes it absolute.
        "CARGO_MANIFEST_DIR": ".",
        "CARGO_PKG_AUTHORS": ":".join(package["authors"]),
        "CARGO_PKG_DESCRIPTION": package.get("description") or "",
        "CARGO_PKG_HOMEPAGE": package.get("homepage") or "",
        "CARGO_PKG_NAME": package["name"],
        "CARGO_PKG_README": package.get("readme") or "",
        "CARGO_PKG_REPOSITORY": package.get("repository") or "",
        "CARGO_PKG_RUST_VERSION": package.get("rust_version") or "",
        "CARGO_PKG_VERSION": version,
        "CARGO_PKG_VERSION_MAJOR": major,
        "CARGO_PKG_VERSION_MINOR": minor,
        "CARGO_PKG_VERSION_PATCH": patch,
        "CARGO_PKG_VERSION_PRE": pre.split("+")[0],
    }


class Resolved:
    """Dependencies and features of one package in one resolution, per host."""

    def __init__(self, workspace, package, resolution, aliases):
        self.normal = {}
        self.dev = {}
        self.features = {}
        for os_name in HOSTS:
            node = workspace.node(resolution, os_name, package)
            self.normal[os_name], self.dev[os_name] = dependency_labels(workspace, package, node)
            self.features[os_name] = sorted(node["features"])
            missing = sorted(
                label.partition(":")[2]
                for label in self.normal[os_name] | self.dev[os_name]
                if label.startswith(THIRD_PARTY_LABEL) and label not in aliases
            )
            if missing:
                raise BuildFileError(
                    f"add to third-party/rust/Cargo.toml: {', '.join(missing)} "
                    f"(dev-dependencies or optional dependencies of {package['name']})"
                )

    def __eq__(self, other):
        return (self.normal, self.dev, self.features) == (other.normal, other.dev, other.features)

    def deps(self, extra=(), with_dev=False):
        return per_host(
            {
                os_name: sorted(set(extra) | self.normal[os_name] | (self.dev[os_name] if with_dev else set()))
                for os_name in HOSTS
            }
        )


def crate_rules(package, directory, resolved, suffix, default):
    """The rules for one feature selection; `suffix` follows each target name."""

    def crate_root(target):
        return Path(target["src_path"]).resolve().relative_to(ROOT / directory).as_posix()

    def env(target=None):
        if target is None:
            return Raw("ENV")
        return Raw(f'ENV | {{"CARGO_BIN_NAME": {json.dumps(target["name"])}}}')

    def test(name, target, environment, deps):
        return call(
            "rust_test",
            {
                "name": name,
                "srcs": Raw('glob(["src/**", "tests/**"])'),
                "crate": target["name"].replace("-", "_"),
                "crate_root": crate_root(target),
                "edition": target["edition"],
                # insta otherwise runs `cargo metadata` to find the workspace root.
                "env": Raw(f'{environment} | {{"INSTA_WORKSPACE_ROOT": "."}}'),
                "features": features,
                # Tests run from the project root and read fixtures through it.
                "run_env": {"CARGO_MANIFEST_DIR": directory},
                "deps": deps,
            },
        )

    def required_features_enabled(target):
        required = set(target.get("required-features") or [])
        enabled = {required <= set(selected) for selected in resolved.features.values()}
        if len(enabled) != 1:
            raise BuildFileError(f"{package['name']}: target {target['name']} has host-dependent required features")
        return enabled.pop()

    features = per_host(resolved.features)
    visibility = ["PUBLIC"] if default else None
    # build_defs/package_release.py archives the binaries labeled `bin`.
    labels = ["bin"] if default else ["all-features"]
    rules = []
    library = library_target(package)
    if library is not None:
        if "proc-macro" in library["kind"]:
            raise BuildFileError(f"{package['name']}: proc-macro crates are not supported")
        rules.append(
            call(
                "rust_library",
                {
                    "name": library["name"] + suffix,
                    "srcs": Raw('glob(["src/**"])'),
                    "crate": library["name"].replace("-", "_"),
                    "crate_root": crate_root(library),
                    "edition": library["edition"],
                    "env": env(),
                    "features": features,
                    "deps": resolved.deps(),
                    # The default-feature library runs the documentation tests.
                    "doctests": library["doctest"] and default,
                    "labels": None if default else labels,
                    "visibility": visibility,
                },
            )
        )
        if library["test"] and default:
            rules.append(test(f"{library['name']}-lib-test", library, env(), resolved.deps(with_dev=True)))

    own_library = [f":{library['name']}{suffix}"] if library is not None else []
    for target in package["targets"]:
        if "bin" in target["kind"]:
            if not required_features_enabled(target):
                continue
            rules.append(
                call(
                    "rust_binary",
                    {
                        "name": f"{target['name']}{suffix}-bin",
                        "srcs": Raw('glob(["src/**"])'),
                        "crate": target["name"].replace("-", "_"),
                        "crate_root": crate_root(target),
                        "edition": target["edition"],
                        "env": env(target),
                        "features": features,
                        "deps": resolved.deps(own_library),
                        "labels": labels,
                        "visibility": visibility,
                    },
                )
            )
            if target["test"] and default:
                rules.append(test(f"{target['name']}-bin-test", target, env(target), resolved.deps(own_library, True)))
        elif "test" in target["kind"] and default:
            rules.append(test(f"{target['name']}-test", target, env(), resolved.deps(own_library, True)))
        elif ("bench" in target["kind"] or "example" in target["kind"]) and default:
            kind = "bench" if "bench" in target["kind"] else "example"
            if kind == "bench" and bench_harness(package, target["name"]):
                raise BuildFileError(f"{package['name']}: bench {target['name']} uses the libtest harness")
            if not required_features_enabled(target):
                continue
            directory_of_root = crate_root(target).split("/")[0]
            rules.append(
                call(
                    "rust_binary",
                    {
                        "name": f"{target['name']}-{kind}",
                        "srcs": Raw(f'glob(["src/**", "{directory_of_root}/**"])'),
                        "crate": target["name"].replace("-", "_"),
                        "crate_root": crate_root(target),
                        "edition": target["edition"],
                        "env": env(),
                        "features": features,
                        "deps": resolved.deps(own_library, True),
                        "labels": [kind],
                    },
                )
            )
    return rules


def bench_harness(package, name):
    """Whether the [[bench]] named `name` uses the libtest harness (Cargo's default)."""
    with open(package["manifest_path"], "rb") as manifest:
        benches = tomllib.load(manifest).get("bench", [])
    for bench in benches:
        if bench.get("name") == name:
            return bench.get("harness", True)
    return True


def crate_build_file(workspace, package, aliases):
    directory = workspace.directories[package["id"]]
    for target in package["targets"]:
        if "custom-build" in target["kind"]:
            raise BuildFileError(f"{package['name']}: build scripts are not supported")

    default = Resolved(workspace, package, "default", aliases)
    all_features = Resolved(workspace, package, "all-features", aliases)
    rules = crate_rules(package, directory, default, "", True)
    if all_features != default:
        rules += crate_rules(package, directory, all_features, "-all-features", False)

    names = [name for name, _ in rules]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise BuildFileError(f"{package['name']}: duplicate target names {', '.join(duplicates)}")

    text = HEADER.format(source=f"{directory}/Cargo.toml")
    if any(rule.startswith("rust_test(") for _, rule in rules):
        text += '\nload("//build_defs:rust_test.bzl", "rust_test")\n'
    text += "\nENV = " + starlark(package_env(package)) + "\n"
    for _, rule in rules:
        text += "\n" + rule
    return directory, text


def main():
    subprocess.run(["reindeer", "buckify"], cwd=ROOT, check=True)
    workspace = Workspace()

    aliases = workspace.third_party_aliases()
    missing_features = workspace.missing_third_party_features()
    if missing_features:
        listing = "; ".join(f"{name}: {', '.join(sorted(features))}" for name, features in sorted(missing_features.items()))
        print(f"error: enable these features in third-party/rust/Cargo.toml: {listing}", file=sys.stderr)
        return 1
    written = set()
    try:
        for package in workspace.crates():
            directory, text = crate_build_file(workspace, package, aliases)
            path = ROOT / directory / "BUCK"
            path.write_text(text, encoding="utf-8")
            written.add(path)
    except BuildFileError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    # Build files of crates that are no longer workspace members.
    for path in (ROOT / "crates").glob("*/BUCK"):
        if path not in written and path.read_text(encoding="utf-8").startswith(GENERATED):
            path.unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main())
