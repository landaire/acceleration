#!/usr/bin/env python3
"""Writes rust_release.bzl, the Rust archives Buck2 downloads.

Records the URL and SHA-256 of each component archive for each supported
host from the release manifests on https://static.rust-lang.org/dist:

- The release that the `channel` of rust-toolchain.toml names: rustc,
  rustdoc, the host standard library, and clippy-driver.
- The nightly that RUSTFMT_NIGHTLY names: rustfmt and the rustc libraries
  it links against. .rustfmt.toml uses options that only a nightly rustfmt
  accepts.

Run it after changing either. With --check, only verifies that
rust_release.bzl was generated for both.
"""

import argparse
import ast
import re
import sys
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUST_TOOLCHAIN_TOML = HERE.parent / "rust-toolchain.toml"
OUTPUT = HERE / "rust_release.bzl"
DIST_URL = "https://static.rust-lang.org/dist"
# Only an exact release pins the same archives for rustup and Buck2;
# `stable` or `1.98` would move for rustup but not for Buck2.
RELEASE_PATTERN = re.compile(r"\d+\.\d+\.\d+")

RUSTFMT_NIGHTLY = "2026-10-14"

RELEASE_COMPONENTS = ["rustc", "rust-std", "clippy-preview"]
RUSTFMT_COMPONENTS = ["rustc", "rustfmt-preview"]

# Buck2 `prelude//os` and `prelude//cpu` constraint names to Rust host
# triples. These are the hosts that reindeer.toml defines platforms for;
# build_defs/update_buck_files.py resolves dependencies for the same.
HOSTS = {
    "linux": {
        "x86_64": "x86_64-unknown-linux-gnu",
    },
    "macos": {
        "arm64": "aarch64-apple-darwin",
    },
    "windows": {
        "x86_64": "x86_64-pc-windows-msvc",
    },
}


def archive(manifest, component, triple):
    entry = manifest["pkg"][component]["target"][triple]
    if not entry.get("available", False):
        raise SystemExit(f"error: {component} is not available for {triple}")
    return entry["xz_url"], entry["xz_hash"]


def render_hosts(name, manifest, components):
    lines = [
        "# os -> cpu -> host triple and component archives.",
        f"{name} = {{",
    ]
    for os_name, cpus in HOSTS.items():
        lines.append(f'    "{os_name}": {{')
        for cpu, triple in cpus.items():
            lines.append(f'        "{cpu}": {{')
            lines.append(f'            "triple": "{triple}",')
            lines.append('            "archives": {')
            for component in components:
                url, sha256 = archive(manifest, component, triple)
                lines.append(f'                "{component}": {{')
                lines.append(f'                    "sha256": "{sha256}",')
                lines.append(f'                    "url": "{url}",')
                lines.append("                },")
            lines.append("            },")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return lines


def render(version, release_manifest, rustfmt_manifest):
    lines = [
        '"""Rust archives that Buck2 downloads.',
        "",
        f"Generated by update_rust_release.py for Rust {version} and the",
        f"{RUSTFMT_NIGHTLY} nightly rustfmt; do not edit.",
        '"""',
        "",
        f'RUST_RELEASE = "{version}"',
        "",
        *render_hosts("RUST_HOSTS", release_manifest, RELEASE_COMPONENTS),
        "",
        f'RUSTFMT_NIGHTLY = "{RUSTFMT_NIGHTLY}"',
        "",
        *render_hosts("RUSTFMT_HOSTS", rustfmt_manifest, RUSTFMT_COMPONENTS),
    ]
    return "\n".join(lines) + "\n"


def pinned_release():
    with open(RUST_TOOLCHAIN_TOML, "rb") as toolchain_file:
        channel = tomllib.load(toolchain_file)["toolchain"]["channel"]
    if not RELEASE_PATTERN.fullmatch(channel):
        raise SystemExit(f"error: {RUST_TOOLCHAIN_TOML} channel {channel!r} is not an exact release")
    return channel


def generated_value(name):
    for node in ast.parse(OUTPUT.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and [t.id for t in node.targets if isinstance(t, ast.Name)] == [name]:
            return ast.literal_eval(node.value)
    raise SystemExit(f"error: {OUTPUT} does not assign {name}")


def load_manifest(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return tomllib.load(response)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify rust_release.bzl without downloading")
    args = parser.parse_args()

    version = pinned_release()
    if args.check:
        expected = {"RUST_RELEASE": version, "RUSTFMT_NIGHTLY": RUSTFMT_NIGHTLY}
        stale = [name for name, value in expected.items() if generated_value(name) != value]
        if stale:
            print(f"error: {OUTPUT.name} is stale ({', '.join(stale)}); run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0

    release_manifest = load_manifest(f"{DIST_URL}/channel-rust-{version}.toml")
    rustfmt_manifest = load_manifest(f"{DIST_URL}/{RUSTFMT_NIGHTLY}/channel-rust-nightly.toml")
    OUTPUT.write_text(render(version, release_manifest, rustfmt_manifest), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
